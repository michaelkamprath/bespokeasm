def _write_config(tmp_path, output_formats=None, annotations=None, fixture='test_instruction_operands.yaml') -> str:
    with open(pkg_resources.files(config_files).joinpath(fixture)) as handle:
        config = YAML(typ='safe').load(handle)
    config['annotations'] = copy.deepcopy(annotations if annotations is not None else {'xmin': XMIN_ANNOTATION})
    if output_formats is not None:
        config['output_formats'] = copy.deepcopy(output_formats)
    path = tmp_path / 'isa.json'
    path.write_text(json.dumps(config))
    return str(path)


def _format_with(**section_overrides) -> dict:
    """The xmin format with options of its symbols section replaced (None removes one)."""
    output_format = copy.deepcopy(XMIN_FORMAT)
    symbols = output_format['sections']['symbols']
    for key, value in section_overrides.items():
        if value is None:
            symbols.pop(key, None)
        else:
            symbols[key] = value
    return {'xmin': output_format}


def _run(tmp_path, source: str, config_path: str, fmt: str | None = 'xmin', pretty: bool = True, explicit=False):
    source_path = tmp_path / 'main.asm'
    source_path.write_text(source)
    output_path = tmp_path / 'out.txt'
    stderr = io.StringIO()
    with contextlib.redirect_stdout(io.StringIO()), contextlib.redirect_stderr(stderr):
        Assembler(
            source_file=str(source_path),
            config_file=config_path,
            generate_binary=False,
            output_file=None,
            binary_start=0,
            binary_end=None,
            binary_fill_value=0,
            enable_pretty_print=pretty,
            pretty_print_format=fmt,
            pretty_print_output=str(output_path),
            is_verbose=0,
            include_paths=[],
            predefined=[],
            pretty_print_format_explicit=explicit,
        ).assemble_bytecode()
    output = output_path.read_text() if output_path.exists() else None
    return output, stderr.getvalue()


def _error(tmp_path, source: str, config_path: str, fmt: str = 'xmin') -> str:
    with pytest.raises(SystemExit) as exc_info:
        _run(tmp_path, source, config_path, fmt)
    return str(exc_info.value)


def _config_error(tmp_path, output_formats, **kwargs) -> str:
    return _error(tmp_path, 'ld a, b, c\n', _write_config(tmp_path, output_formats, **kwargs), fmt='listing')


# ---- templates ----------------------------------------------------------------------

def _fail(problem):
    raise ValueError(problem)


TEMPLATE_FIELDS = {'name': 'x', 'count': 0, 'address': 0, 'section': NO_FORMAT_SPEC}


@pytest.mark.parametrize(('text', 'values', 'expected'), [
    ('{name}', {'name': 'pa'}, 'pa'),
    ('0x{address:04x}', {'address': 0x113}, '0x0113'),
    ('{name:>5}|', {'name': 'pa'}, '   pa|'),
    ('{{literal}} {name}', {'name': 'pa'}, '{literal} pa'),
    ('{name}{?[{count}]}', {'name': 'buf', 'count': 16}, 'buf[16]'),
    ('{name}{?[{count}]}', {'name': 'pa', 'count': None}, 'pa'),
    ('{name}{?[{count}]}', {'name': 'pa'}, 'pa'),
    ('{?{name}={count:02x}}', {'name': 'a', 'count': 0}, 'a=00'),
    ('{?{{{name}}}}', {'name': 'a'}, '{a}'),
    ('[{address:04x}]', {'address': None}, '[]'),
    ('[{name}]', {'name': ''}, '[]'),
    ('{section}', {'section': 'line 1\nline 2'}, 'line 1\nline 2'),
])
def test_template_render(text, values, expected):
    assert Template.parse(text, TEMPLATE_FIELDS, _fail).render(values) == expected


@pytest.mark.parametrize(('text', 'problem'), [
    ('{nmae}', 'uses unknown field "nmae"; known fields are address, count, name, section'),
    ('{name.upper}', 'has an invalid field "{name.upper}"'),
    ('{name!r}', 'has an invalid field "{name!r}"'),
    ('{?[{count}]', 'has an optional group "{?" with no closing "}"'),
    ('{?a{?{count}}}', 'nests an optional group'),
    ('{?[]}', 'has an optional group "{?...}" with no fields in it'),
    ('name}', 'has a single "}"'),
    ('{name', 'has a "{" with no closing "}"'),
    ('{address:q}', 'gives field "address" the format spec "q", which does not apply to it'),
    ('{name:04x}', 'gives field "name" the format spec "04x", which does not apply to it'),
    ('{section:>4}', 'gives field "section" a format spec, which it does not take'),
])
def test_template_errors(text, problem):
    with pytest.raises(ValueError) as exc_info:
        Template.parse(text, TEMPLATE_FIELDS, _fail)
    assert problem in str(exc_info.value)


